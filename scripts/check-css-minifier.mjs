import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import * as csstree from 'css-tree';
globalThis.csstree = csstree;
await import('../js/css-minifier.js');
const { minify, MAX_INPUT_LENGTH, MAX_DEPTH, SAMPLE } = globalThis.MarkBenchCssMinifier;
const output = (source, options) => {
  const result = minify(source, options);
  assert.equal(result.state, 'ready', result.error);
  return result.output;
};
assert.equal(output('/* comment */ .a { color: #ffffff; margin: 0px auto; }'), '.a{color:#ffffff;margin:0px auto}');
assert.equal(output('.a { color: red; }', { omitSemicolon: false }), '.a{color:red;}');
assert.equal(output('/*! license */ /* remove */ .a { color: red; }'), '/*! license */.a{color:red}');
assert.equal(output('/*! license */ .a { color: red; }', { keepLicense: false }), '.a{color:red}');
assert.equal(output('.a { /*! inner license */ color:red; }'), '/*! inner license */.a{color:red}');
assert.equal(output('@charset "UTF-8"; /*! license */ .a {color:red}'), '@charset "UTF-8";/*! license */.a{color:red}');
assert.match(output('.a { width: calc(100% - 2px); height: calc(1px + 2px); }'), /calc\(100% - 2px\)/u);
assert.equal(output('.parent .child:hover > span { color:red; }'), '.parent .child:hover>span{color:red}');
assert.equal(output('.a { content: "/* text */ ; }  "; }'), '.a{content:"/* text */ ; }  "}');
assert.equal(output('.a { content: "quote\\\" and \\\\"; }'), '.a{content:"quote\\\" and \\\\"}');
assert.equal(csstree.parse(output('.a { background: url("data:image/svg+xml,<svg><!-- x --></svg>"); }')).children.first.block.children.first.value.children.first.value, 'data:image/svg+xml,<svg><!-- x --></svg>');
assert.match(output('.a { background: url(data:image/png;base64,AAA); }'), /url\(data:image\/png;base64,AAA\)/u);
assert.equal(output(':root { --blank: ; --words: A/**/B; --theme: { color: red }; }'), ':root{--blank: ;--words: A/**/B;--theme: { color: red }}');
assert.match(output('.a { color: var(--x, red  blue); }'), /var\(--x, red  blue\)/u);
assert.equal(output('.a { & .b { color:red; } color:blue; }'), '.a{& .b{color:red}color:blue}');
assert.equal(output('.a { div:hover { .b { color: red; } } color:blue; }'), '.a{div:hover{.b{color:red}}color:blue}');
assert.equal(output('@layer base { @container (width > 20rem) { .a { color: light-dark(white, black); } } }'), '@layer base{@container (width>20rem){.a{color:light-dark(white,black)}}}');
assert.equal(output('@media screen and (min-width: 1px) { .a {color:red} }'), '@media screen and (min-width:1px){.a{color:red}}');
assert.equal(output('.\\31 0 { --x: /*! preserve raw */ x; }', { keepLicense: false }), '.\\31 0{--x: /*! preserve raw */ x}');
assert.equal(output('.a { color:red; color:blue; }'), '.a{color:red;color:blue}');
for (const source of ['', ' \n\t']) assert.equal(minify(source).state, 'empty');
assert.equal(output('/* only comment */'), '');
for (const source of ['a{color red}', 'a{color:red', 'a{color:red}}', 'a{content:"x}', 'a{content:"x\n"}', '/* unclosed', 'a{background:url(x}', 'a{width:calc(1px + 2px]}', 'not CSS']) {
  const result = minify(source);
  assert.equal(result.state, 'invalid', source);
  assert.equal(result.output, '');
  assert.ok(result.line >= 1 && result.column >= 1);
}
assert.match(minify('a{\n content:"missing\n}').error, /2行/u);
assert.equal(minify('/*' + 'x'.repeat(MAX_INPUT_LENGTH - 4) + '*/').state, 'ready');
assert.equal(minify(' '.repeat(MAX_INPUT_LENGTH + 1)).state, 'invalid');
assert.equal(minify('.a{'.repeat(MAX_DEPTH) + 'color:red' + '}'.repeat(MAX_DEPTH)).state, 'ready');
assert.equal(minify('.a{'.repeat(MAX_DEPTH + 1) + 'color:red' + '}'.repeat(MAX_DEPTH + 1)).state, 'invalid');
const japanese = minify('.a { content: "日本語😀"; }');
assert.equal(japanese.inputBytes, Buffer.byteLength('.a { content: "日本語😀"; }'));
assert.equal(japanese.outputBytes, Buffer.byteLength(japanese.output));
assert.equal(japanese.savedBytes, japanese.inputBytes - japanese.outputBytes);
assert.equal(output(SAMPLE), output(output(SAMPLE)));
assert.equal(minify('.a{color:red}', { omitSemicolon: false }).savedBytes, -1);
for (let i = 0; i < 50; i++) assert.equal(output(SAMPLE), output(SAMPLE));
assert.equal(await readFile(new URL('../js/vendor/csstree.js', import.meta.url), 'utf8'), await readFile(new URL('../node_modules/css-tree/dist/csstree.js', import.meta.url), 'utf8'));
assert.equal(await readFile(new URL('../js/vendor/css-tree-LICENSE.txt', import.meta.url), 'utf8'), await readFile(new URL('../node_modules/css-tree/LICENSE', import.meta.url), 'utf8'));
console.log('CSS Minifier checks passed: token boundaries, nesting, variables, licenses, UTF-8 metrics, limits, malformed input and vendor integrity.');
